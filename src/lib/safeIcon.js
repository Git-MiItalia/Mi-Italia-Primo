/* Returns the name when the font can draw it, otherwise the fallback.
 *
 * Only for names the portal did not choose itself — an icon written in our own
 * code belongs in the list above, not behind this guard, so that a typo shows
 * up rather than being quietly swallowed by a fallback. */
export function safeIcon(name, fallback = 'help') {
  return BAKED.has(String(name ?? '').trim()) ? name : fallback
}

export function isBakedIcon(name) {
  return BAKED.has(String(name ?? '').trim())
}
